#!/usr/bin/env python3
# Generates the Arduino library "Pico2DVI" (<=7 files) by merging the vendored
# Pico SDK libdvi sources in this repo. Run from the repo root: python3 build_lib.py
import re, os

SRC = '.'
OUT = 'Pico2DVI/src'
os.makedirs(OUT, exist_ok=True)

def read(p): return open(os.path.join(SRC, p)).read()

# ---------------------------------------------------------------- dvi_core.h
parts = []
for p in ['dvi_config_defs.h', 'util_queue_u32_inline.h', 'dvi_serialiser.h',
          'dvi_timing.h', 'dvi.h']:
    s = read(p)
    s = re.sub(r'#ifndef _\w+\n#define _\w+\n', '', s)
    s = re.sub(r'#endif\s*$', '', s.rstrip())
    s = re.sub(r'#include "(dvi_config_defs|util_queue_u32_inline|dvi_serialiser|dvi_timing|dvi|dvi_data_island)\.h"',
               '// (merged into this header)', s)
    parts.append(s.strip())

core = '''// dvi_core.h -- libdvi (PicoDVI) core API, merged for the Arduino IDE port.
// Target board: Waveshare RP2350-PiZero on the earlephilhower arduino-pico
// core (that core ships the full pico-sdk hardware API: pio/dma/interp/pwm).
// BSD-3-Clause (C) 2021 Luke Wren; MIT portions (C) Shuichi Takano --
// see LICENSE / PROVENANCE.md in the repository.
//
// This ONE header merges the following original Pico SDK library files:
//   dvi_config_defs.h, util_queue_u32_inline.h, dvi_serialiser.h,
//   dvi_timing.h, dvi.h, common_dvi_pin_configs.h
// The generated PIO program headers + TMDS LUTs are in dvi_pio_merged.h
// (included at the bottom), and the public C++ wrapper is Pico2DVI.h.
#ifndef _DVI_CORE_H
#define _DVI_CORE_H

#include <stdint.h>
#include <stdbool.h>

''' + '\n\n'.join(parts) + '''

// ----------------------------------------------------------------------------
// Generated PIO programs + TMDS lookup tables (merged pioasm output)
#include "dvi_pio_merged.h"

// ----------------------------------------------------------------------------
// Board pin configs (merged from common_dvi_pin_configs.h).
// Waveshare RP2350-PiZero onboard HDMI: TMDS data pairs GPIO 32..37,
// clock pair GPIO 38/39. Lane order is {blue, green, red} (blue = sync lane).

#ifndef DVI_DEFAULT_PIO_INST
#define DVI_DEFAULT_PIO_INST pio0
#endif

static const struct dvi_serialiser_cfg waveshare_rp2350_pizero_cfg = {
        .pio = DVI_DEFAULT_PIO_INST,
        .sm_tmds = {0, 1, 2},
        .pins_tmds = {36, 34, 32},   // {blue, green, red} (each pair: n, n+1)
        .pins_clk = 38,              // clock pair 38/39
        .invert_diffpairs = false
};

#ifndef DVI_DEFAULT_SERIAL_CONFIG
#define DVI_DEFAULT_SERIAL_CONFIG waveshare_rp2350_pizero_cfg
#endif

#endif // _DVI_CORE_H
'''
open(os.path.join(OUT, 'dvi_core.h'), 'w').write(core)

# ---------------------------------------------------------- dvi_pio_merged.h
def strip_gen(s):
    s = re.sub(r'^// -+ //\n// This file is autogenerated.*\n// -+ //\n\n', '', s)
    s = s.replace('#pragma once\n', '')
    s = re.sub(r'#if !PICO_NO_HARDWARE\n#include "hardware/pio\.h"\n#endif\n', '', s)
    s = re.sub(r'#if !PICO_NO_HARDWARE\n', '', s)
    s = s.replace('\n#endif\n', '\n')  # closing of PICO_NO_HARDWARE blocks
    return s.strip()

ser = strip_gen(read('dvi_serialiser.pio.h'))
onebpp = strip_gen(read('tmds_encode_1bpp.pio.h'))

# Table bodies: everything after the leading comment block (they are bare lists)
def table_body(p):
    lines = read(p).splitlines()
    out = [l for l in lines if not l.startswith('//') and not l.startswith('//')]
    return '\n'.join(out).strip()

pio = '''// dvi_pio_merged.h -- generated PIO program headers and TMDS encode lookup
// tables, merged from pioasm output (dvi_serialiser.pio.h,
// tmds_encode_1bpp.pio.h) plus tmds_table.h / tmds_table_fullres.h.
// Regenerate with `pioasm` if the .pio sources change. Do not hand-edit.
// Part of the Pico2DVI Arduino library (BSD-3-Clause, see LICENSE).
#pragma once

#include <stdint.h>
#include "hardware/pio.h"

''' + ser + '\n\n' + onebpp + '''

// ----------------------------------------------------------------------------
// TMDS encode lookup tables

// 6-bit -> pixel-doubled symbol pair table (tmds_table.h body)
extern "C" const uint32_t tmds_table[] = {
''' + table_body('tmds_table.h') + '''};

// Full-resolution (running-disparity) tables used from scratch X/Y or main
// SRAM (tmds_table_fullres.h body, included twice as upstream does)
#define P2DVI_TMDS_FULLRES_TABLE ''' + table_body('tmds_table_fullres.h') + '''

extern "C" const uint32_t tmds_table_fullres_x[];
extern "C" const uint32_t tmds_table_fullres_y[];
'''
open(os.path.join(OUT, 'dvi_pio_merged.h'), 'w').write(pio)
print('generated headers')
