#!/usr/bin/env python3
# Assembles the Pico2DVI Arduino library (7 files) from the vendored libdvi.
import re, os

SRC = '.'
OUT = 'Pico2DVI/src'
os.makedirs(OUT, exist_ok=True)

def read(p): return open(os.path.join(SRC, p)).read()
def write(p, s): open(os.path.join(OUT, p), 'w').write(s)

LICENSE_HDR = ('// Part of the Pico2DVI Arduino library -- port of Wren6991/PicoDVI\n'
               '// libdvi (BSD-3-Clause (C) 2021 Luke Wren; MIT portions (C) Shuichi\n'
               '// Takano) to the earlephilhower arduino-pico core. See LICENSE.\n')

# ---------------------------------------------------------------- dvi_core.h
parts = []
for p in ['dvi_config_defs.h', 'util_queue_u32_inline.h', 'dvi_serialiser.h',
          'dvi_timing.h', 'dvi.h']:
    s = read(p)
    s = re.sub(r'#ifndef _\w+\n#define _\w+\n', '', s)
    s = re.sub(r'#endif\s*$', '', s.rstrip())
    s = re.sub(r'#include "(dvi_config_defs|util_queue_u32_inline|dvi_serialiser|dvi_timing|dvi|dvi_data_island)\.h"',
               '// (merged into this header)', s)
    parts.append(s.strip())

core = '''// dvi_core.h -- libdvi (PicoDVI) core API, merged for the Arduino IDE port.
// Target board: Waveshare RP2350-PiZero on the earlephilhower arduino-pico
// core (that core ships the pico-sdk hardware API: pio/dma/interp/pwm/gpio).
// BSD-3-Clause (C) 2021 Luke Wren; MIT portions (C) Shuichi Takano --
// see LICENSE / PROVENANCE.md in the repository.
//
// This ONE header merges these original Pico SDK library files:
//   dvi_config_defs.h, util_queue_u32_inline.h, dvi_serialiser.h,
//   dvi_timing.h, dvi.h, common_dvi_pin_configs.h
// Generated PIO headers + TMDS LUT bodies live in dvi_pio_merged.h.
#ifndef _DVI_CORE_H
#define _DVI_CORE_H

#include <stdint.h>
#include <stdbool.h>

''' + '\n\n'.join(parts) + '''

// ----------------------------------------------------------------------------
// Generated PIO programs + TMDS lookup tables (merged pioasm output)
#include "dvi_pio_merged.h"

// ----------------------------------------------------------------------------
// Board pin config (merged from common_dvi_pin_configs.h).
// Waveshare RP2350-PiZero onboard HDMI: TMDS data pairs GPIO 32..37,
// clock pair GPIO 38/39. Lane order is {blue, green, red} (blue = sync lane).

#ifndef DVI_DEFAULT_PIO_INST
#define DVI_DEFAULT_PIO_INST pio0
#endif

static const struct dvi_serialiser_cfg waveshare_rp2350_pizero_cfg = {
        .pio = DVI_DEFAULT_PIO_INST,
        .sm_tmds = {0, 1, 2},
        .pins_tmds = {36, 34, 32},   // {blue, green, red}; each pair is n, n+1
        .pins_clk = 38,              // clock pair 38/39
        .invert_diffpairs = false
};

#ifndef DVI_DEFAULT_SERIAL_CONFIG
#define DVI_DEFAULT_SERIAL_CONFIG waveshare_rp2350_pizero_cfg
#endif

#endif // _DVI_CORE_H
'''
write('dvi_core.h', core)

# ---------------------------------------------------------- dvi_pio_merged.h
def strip_gen(s):
    s = re.sub(r'^// -+ //\n// This file is autogenerated.*\n// -+ //\n\n', '', s)
    s = s.replace('#pragma once\n', '')
    s = re.sub(r'#if !PICO_NO_HARDWARE\n#include "hardware/pio\.h"\n#endif\n', '', s)
    s = re.sub(r'#if !PICO_NO_HARDWARE\n', '', s)
    s = s.replace('\n#endif\n', '\n')
    return s.strip()

def table_body(p):
    lines = read(p).splitlines()
    out = [l for l in lines if not l.startswith('//')]
    return '\n'.join(out).strip()

pio = '''// dvi_pio_merged.h -- generated PIO program headers and TMDS encode lookup
// tables, merged from pioasm output (dvi_serialiser.pio.h,
// tmds_encode_1bpp.pio.h) plus tmds_table.h / tmds_table_fullres.h.
// Regenerate with `pioasm` if the .pio sources change. Do not hand-edit.
''' + LICENSE_HDR + '''
#pragma once

#include <stdint.h>
#include "hardware/pio.h"

''' + strip_gen(read('dvi_serialiser.pio.h')) + '\n\n' + \
    strip_gen(read('tmds_encode_1bpp.pio.h')) + '''

// ----------------------------------------------------------------------------
// TMDS encode lookup tables. The full-resolution table needs a copy in each
// scratch X/Y window (or main SRAM); those definitions live in tmds_encode.cpp.

#define P2DVI_TMDS_TABLE_BODY \\
''' + '\n'.join(table_body('tmds_table.h').splitlines()) + '''

#define P2DVI_TMDS_FULLRES_TABLE_BODY \\
''' + '\n'.join(table_body('tmds_table_fullres.h').splitlines()) + '''
'''
write('dvi_pio_merged.h', pio)

# ------------------------------------------------------------ Pico2DVI.h
p2h = '''// Pico2DVI.h -- Arduino wrapper for libdvi (PicoDVI) on the Waveshare
// RP2350-PiZero (earlephilhower arduino-pico core). Displays an RGB565
// picture over DVI/HDMI using PIO + DMA, driven from a second core.
''' + LICENSE_HDR + '''
#ifndef _PICO2DVI_H
#define _PICO2DVI_H

#include "dvi_core.h"

// Built-in test pattern resolution (double-res mode: 320x240 pixels are
// scaled x2 by DVI_VERTICAL_REPEAT to fill a 640x480 VGA frame).
#define P2DVI_IMG_W 320
#define P2DVI_IMG_H 240

class Pico2DVI {
public:
        // Start DVI output showing a colour-bar test pattern. Call from setup().
        // Returns false only on unrecoverable init failure.
        static bool begin();

        // Push a 320x240 RGB565 image (row-major, stride 320) to the screen.
        // Thread-safe: copies into the internal front/back buffer.
        static void drawImage(const uint16_t *rgb565);

        // Draw one pixel into the pending back buffer (x,y RGB565), then call
        // show() to flip it onto the screen.
        static void setPixel(uint16_t x, uint16_t y, uint16_t rgb565);
        static void clear(uint16_t rgb565);
        static void show();

        // Fill whole screen immediately.
        static void fill(uint16_t rgb565);

        static struct dvi_inst inst;

private:
        static void encoderCore(void *arg);      // runs forever on core 1
        static volatile uint16_t *frontbuf;      // sampled by core 1 each frame
        static uint16_t bufs[2][P2DVI_IMG_W * P2DVI_IMG_H];
        static uint16_t back;
};

#endif // _PICO2DVI_H
'''
write('Pico2DVI.h', p2h)

print('headers ok:', os.listdir(OUT))
